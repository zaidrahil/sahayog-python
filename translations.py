LANGUAGE_NAME_MAP = {code: f"{flag} {native}" for code, native, _, flag in SUPPORTED_LANGUAGES}


def translate(key, lang="en"):
    """Lookup a translated string with graceful fallback to English and then key itself."""
    if not lang or lang not in TRANSLATIONS:
        lang = "en"
    return TRANSLATIONS[lang].get(key, TRANSLATIONS["en"].get(key, key))


def translate_category(category_id, lang="en"):
    """Translate a service trade category (e.g. 'electrician' -> 'इलेक्ट्रीशियन')."""
    if not lang or lang not in CATEGORY_TRANSLATIONS:
        lang = "en"
    return CATEGORY_TRANSLATIONS[lang].get(
        category_id, CATEGORY_TRANSLATIONS["en"].get(category_id, category_id.replace("_", " ").title())
    )


def get_language_info(code):
    for item in SUPPORTED_LANGUAGES:
        if item[0] == code:
            return {
                "code": item[0],
                "native_name": item[1],
                "english_name": item[2],
                "flag": item[3],
                "display": f"{item[3]} {item[1]}",
            }
    return {
        "code": "en",
        "native_name": "English",
        "english_name": "English",
        "flag": "🇬🇧",
        "display": "🇬🇧 English",
    }
